'use strict';
// Taxonomy is authored once; schema projections and browser labels/types are generated.
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.resolve(__dirname, '../../..');
const {resolvePaths} = require('../../../atlas.config.cjs');
const schemaRoot = resolvePaths(root).cryptanalysisSchemas;
const registryFile = path.join(schemaRoot, 'result-taxonomy.json');
function validateTaxonomy(taxonomy, schema) {
  const check = (ok, message) => { if (!ok) throw new Error('Invalid result taxonomy: ' + message); };
  const object = value => value && typeof value === 'object' && !Array.isArray(value);
  const text = value => typeof value === 'string' && value.trim().length > 0;
  const shape = (value, required, optional, where) => {
    check(object(value), where + ' must be an object');
    check(required.every(key => Object.hasOwn(value, key)), where + ' missing required fields');
    check(Object.keys(value).every(key => required.includes(key) || optional.includes(key)), where + ' has unknown fields');
  };
  shape(taxonomy, ['schema_versions', 'legacy_version', 'kinds', 'goals', 'methods', 'key_models', 'attack_surfaces'], [], 'registry');
  check(Array.isArray(taxonomy.schema_versions) && taxonomy.schema_versions.length > 0
    && taxonomy.schema_versions.every(v => typeof v === 'string' && /^\d+\.\d+\.\d+$/.test(v))
    && new Set(taxonomy.schema_versions).size === taxonomy.schema_versions.length, 'invalid schema_versions');
  check(taxonomy.schema_versions[0] === taxonomy.legacy_version, 'legacy_version must be the first supported version');
  for (let i = 1; i < taxonomy.schema_versions.length; i++) {
    const previous = taxonomy.schema_versions[i - 1].split('.').map(Number), current = taxonomy.schema_versions[i].split('.').map(Number);
    const different = current.findIndex((value, index) => value !== previous[index]);
    check(different >= 0 && current[different] > previous[different], 'schema_versions must be ordered oldest to newest');
  }
  for (const group of ['kinds', 'goals', 'methods', 'key_models', 'attack_surfaces']) {
    check(object(taxonomy[group]) && Object.keys(taxonomy[group]).length > 0, group + ' must be a nonempty map');
    check(Object.keys(taxonomy[group]).every(id => /^[a-z][a-z0-9_]*$/.test(id)), group + ' contains an invalid ID');
  }
  for (const [id, kind] of Object.entries(taxonomy.kinds)) {
    shape(kind, ['label', 'section', 'comparable'], [], id);
    check(text(kind.label) && ['costs', 'bounds', 'properties'].includes(kind.section) && typeof kind.comparable === 'boolean', id + ' invalid kind contract');
    check(!kind.comparable || kind.section === 'costs', id + ' comparable kinds must use the costs section');
  }
  for (const group of ['methods', 'key_models', 'attack_surfaces']) for (const label of Object.values(taxonomy[group])) check(text(label), group + ' has a blank label');
  for (const [id, goal] of Object.entries(taxonomy.goals)) {
    shape(goal, ['label', 'kind'], ['legacy', 'required', 'known_key', 'construction_type', 'metric', 'key_model'], id);
    check(text(goal.label) && Object.hasOwn(taxonomy.kinds, goal.kind), id + ' invalid label or kind');
    for (const flag of ['legacy', 'known_key']) if (Object.hasOwn(goal, flag)) check(typeof goal[flag] === 'boolean', id + ' ' + flag + ' must be boolean');
    const fields = goal.required ?? [];
    check(Array.isArray(fields) && new Set(fields).size === fields.length && fields.every(field => ['candidate_space', 'property', 'bound', 'experiment', 'theorem'].includes(field) && Object.hasOwn(schema.properties, field)), id + ' invalid required payload');
    if (goal.key_model !== undefined) check(Object.hasOwn(taxonomy.key_models, goal.key_model), id + ' unknown key_model');
    if (goal.construction_type !== undefined) check(fields.includes('experiment') && schema.$defs.experiment.properties.construction.properties.type.enum.includes(goal.construction_type), id + ' invalid construction_type');
    if (goal.metric !== undefined) check(fields.includes('theorem') && text(goal.metric), id + ' metric requires theorem');
    check(!fields.includes('theorem') || goal.kind === 'theorem', id + ' theorem payload requires theorem kind');
    check(goal.kind !== 'theorem' || fields.includes('theorem') && text(goal.metric), id + ' theorem kind requires payload and metric');
    check(!(fields.includes('experiment') && fields.includes('theorem')), id + ' cannot mix experiment and theorem payloads');
    check(!goal.legacy || !fields.some(field => ['experiment', 'theorem'].includes(field)), id + ' legacy goal cannot require a new payload');
  }
}
function projections(taxonomy, schema) {
  validateTaxonomy(taxonomy, schema);
  const s = structuredClone(schema);
  s.$comment = 'Taxonomy projections generated by scripts/sync-result-model.cjs; SHA256 ' + crypto.createHash('sha256').update(JSON.stringify(taxonomy)).digest('hex');
  s.properties.schema_version = {enum: taxonomy.schema_versions};
  s.properties.result_kind.enum = Object.keys(taxonomy.kinds);
  s.properties.goal.enum = Object.keys(taxonomy.goals);
  s.properties.display.properties.method.enum = Object.keys(taxonomy.methods);
  s.properties.setting.properties.key_model.enum = Object.keys(taxonomy.key_models);
  s.properties.setting.properties.attack_surface.enum = Object.keys(taxonomy.attack_surfaces);
  s.$defs.registered_goal = {type: 'object', oneOf: Object.entries(taxonomy.goals).map(([goal, contract]) => ({
    properties: {goal: {const: goal}, result_kind: {const: contract.kind}, experiment: false, theorem: false,
      ...Object.fromEntries((contract.required ?? []).map(field => [field, {}])),
      ...(contract.metric ? {theorem: {type: 'object', properties: {metric: {const: contract.metric}}}} : {}),
      ...(contract.construction_type ? {experiment: {type: 'object', properties: {construction: {type: 'object', properties: {type: {const: contract.construction_type}}}}}} : {}),
      ...(contract.key_model ? {setting: {type: 'object', properties: {key_model: {const: contract.key_model}}}} : {})},
    required: ['goal', 'result_kind', ...(contract.required ?? [])]
  }))};
  s.$defs.legacy_result = {type: 'object', properties: {
    goal: {enum: Object.entries(taxonomy.goals).filter(([,goal]) => goal.legacy).map(([id]) => id)},
    experiment: false, theorem: false,
    target: {type: 'object', properties: {rounds: {type: 'number'}, full_round: {type: 'boolean'}, round_domain: false}}
  }};
  const ts = '// Generated by npm run sync:analysis-model. Do not edit.\n'
    + 'export const resultTaxonomy = ' + JSON.stringify(taxonomy, null, 2) + ' as const;\n'
    + 'export type AnalysisGoal = keyof typeof resultTaxonomy.goals;\n'
    + 'export type AnalysisResultKind = keyof typeof resultTaxonomy.kinds;\n'
    + 'export type AnalysisMethod = keyof typeof resultTaxonomy.methods;\n'
    + 'export type KeyModel = keyof typeof resultTaxonomy.key_models;\n'
    + 'export type AttackSurface = keyof typeof resultTaxonomy.attack_surfaces;\n';
  return {schema: JSON.stringify(s, null, 2) + '\n', typescript: ts};
}
function sync(write = false) {
  const registry = JSON.parse(fs.readFileSync(registryFile, 'utf8'));
  const schemaFile = path.join(schemaRoot, 'result.schema.json');
  const output = projections(registry, JSON.parse(fs.readFileSync(schemaFile, 'utf8')));
  const outputs = [[schemaFile, output.schema], [path.join(root, 'src/features/cryptanalysis/taxonomy.ts'), output.typescript]];
  const stale = outputs.filter(([file, value]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== value);
  if (write) for (const [file, value] of stale) fs.writeFileSync(file, value);
  else if (stale.length) throw new Error('Stale result-model projections; run npm run sync:analysis-model: ' + stale.map(([file]) => path.relative(root, file)).join(', '));
  return stale.length;
}
if (require.main === module) { const n = sync(process.argv.includes('--write')); console.log('PASS: result taxonomy/schema/types ' + (process.argv.includes('--write') ? 'synchronized (' + n + ' files)' : 'in sync')); }
module.exports = {projections, sync, validateTaxonomy};
