'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const {resolvePaths} = require('../../../atlas.config.cjs');
const {validateDataset} = require('./check-data.cjs');
const {publicationPatterns, assertPublicText, publicCopy} = require('../publication-safety.cjs');
const {createPublicationPolicy, documentForFile} = require('./publication-policy.cjs');

const json = value => JSON.stringify(value, null, 2) + '\n';
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const pick = (value, keys) => Object.fromEntries(keys.filter(key => Object.hasOwn(value, key)).map(key => [key, value[key]]));
const approvedFile = name => /^(?:manifest|sources|ciphers|variants|coverage|witnesses)\.json$/.test(name)
  || /^(?:results|result-families|presentation|problem-results|problem-analyses)\/[a-z0-9-]+\.json$/.test(name)
  || /^entries\/[a-z0-9-]+\.jsonl$/.test(name) || name === 'README.md';
const readJson = file => JSON.parse(fs.readFileSync(file, 'utf8'));
const notice = `# Published cryptanalysis snapshot

Generated by \`npm run export:analyses\`; do not hand-edit this directory.
The maintained research corpus is separate and is not needed to build this snapshot.

The project's original selection, organization, metadata and editorial text in
this directory are licensed under CC BY 4.0. Attribute CryptoFrontierAtlas and
the release contributors, link to the release and license, retain scholarly
citations, and identify changes. See ../../LICENSE-CC-BY-4.0.txt for the unchanged
license terms. Cited publications and third-party artifacts retain their rights.

Publication does not upgrade a claim's review or reproduction status. Local audit
references are explicitly marked as not distributed; primary-source versions,
page/table locators, limitations and conflicts are retained. Full papers and
internal ingestion reports are not included.
`;

function fileInventory(directory) {
  const result = [];
  function visit(relative = '') {
    const file = path.join(directory, relative), info = fs.lstatSync(file);
    assert(!info.isSymbolicLink(), 'Published data refuses symlinks');
    if (info.isDirectory()) for (const name of fs.readdirSync(file).sort()) visit(relative ? relative + '/' + name : name);
    else { assert(info.isFile(), 'Published data requires regular files'); result.push(relative); }
  }
  visit(); return result;
}
function counts(data) {
  return {records: data.results.length, entries: data.entries.length,
    compact_only: data.entries.filter(entry => entry.record_id === null).length,
    parameterized_families: data.familyCatalogs.reduce((sum, catalog) => sum + catalog.families.length, 0),
    sources: data.sources.length, ciphers: data.ciphers.length, instances: data.variants.length,
    ...((data.problemAnalyses ?? []).length ? {hard_problems: data.problemAnalyses.length,
      problem_records: data.problemAnalyses.reduce((n, c) => n + c.results.length, 0),
      problem_families: data.problemAnalyses.reduce((n, c) => n + c.families.length, 0)} : {})};
}
function scientificDigest(data, root = path.resolve(__dirname, '../../..')) {
  // Paths in editorial evidence may be projected; experimental inputs, costs,
  // success, bounds and parameterized models must remain byte-for-byte equivalent.
  const fields = ['id', 'result_kind', 'goal', 'target', 'setting', 'techniques', 'resources', 'success',
    'candidate_space', 'bound', 'experiment', 'theorem', 'display', 'assessment'];
  const evidence = record => ({
    evidence: record.evidence?.map(item => pick(item, ['source_id', 'fields'])),
    property: publicCopy(record.property),
    field_conflicts: publicCopy(record.field_conflicts),
  });
  const problemPolicy = data.problemAnalyses?.length ? createPublicationPolicy(root) : null;
  return sha256(json({results: data.results.map(r => ({...pick(r, fields), ...evidence(r)})),
    entries: data.entries.map(e => ({...pick(e, [...fields, 'source_id', 'source_sha256', 'method', 'record_id']), ...evidence(e)})),
    catalogs: data.familyCatalogs.map(c => ({cipher_family_id: c.cipher_family_id,
      families: c.families.map(f => pick(f, ['id', 'representation', 'parameters', 'points', 'model'])),
      standalone_result_ids: c.standalone_result_ids, excluded_results: c.excluded_results})),
    sources: data.sources.map(s => pick(s, ['id', 'content_sha256', 'artifact_sha256'])),
    ciphers: data.ciphers, variants: data.variants,
    ...((data.problemAnalyses ?? []).length ? {problemAnalyses: data.problemAnalyses.map(({results, ...catalog}) => ({
      ...problemPolicy.project('problem-analysis', catalog), results: results.map(r => problemPolicy.project('problem-result', r)),
    }))} : {})}));
}
function shape(value, allowed, label) {
  assert(value && !Array.isArray(value) && typeof value === 'object', `${label}: expected object`);
  assert(Object.keys(value).every(key => allowed.includes(key)), `${label}: unapproved field`);
}
function validatePublicShape(directory, root = path.resolve(__dirname, '../../..'), policy = createPublicationPolicy(root)) {
  for (const file of fileInventory(directory)) {
    if (file === 'README.md' || file === 'publication.json') continue;
    const {document, many} = documentForFile(file);
    const value = file.endsWith('.jsonl')
      ? fs.readFileSync(path.join(directory, file), 'utf8').split(/\r?\n/).filter(line => line.trim()).map(JSON.parse)
      : readJson(path.join(directory, file));
    if (many || file.endsWith('.jsonl')) {
      assert(Array.isArray(value), 'Expected public document array');
      for (const item of value) policy.assertPublic(document, item);
    } else policy.assertPublic(document, value);
  }
  const coverage = readJson(path.join(directory, 'coverage.json'));
  assert(Object.values(coverage.review_process).every(value => typeof value === 'string'), 'Review process must contain text');
  assert.deepEqual(coverage.ingestion_batches, [], 'Public coverage must not contain ingestion receipts');
  for (const issue of coverage.issues) if (issue.bounded_checks) {
    assert(Object.values(issue.bounded_checks).every(value => typeof value === 'boolean' || Number.isInteger(value) && value >= 0),
      'Bounded checks must contain boolean flags or counts');
  }
}

function makePublishedFiles(root) {
  const policy = createPublicationPolicy(root);
  const locations = resolvePaths(root);
  // Reject redirected inputs before the shared validator reads any public data.
  const regular = (file, directory = false) => {
    const info = fs.lstatSync(file);
    assert(!info.isSymbolicLink() && (directory ? info.isDirectory() : info.isFile()), 'Snapshot export refuses redirected or non-regular inputs');
  };
  regular(path.dirname(locations.cryptanalysis), true);
  regular(locations.cryptanalysis, true);
  for (const file of ['manifest', 'sources', 'ciphers', 'variants', 'coverage', 'witnesses']) regular(path.join(locations.cryptanalysis, file + '.json'));
  for (const folder of ['results', 'entries', 'result-families', 'presentation', 'problem-results', 'problem-analyses']) {
    const directory = path.join(locations.cryptanalysis, folder);
    if (!fs.existsSync(directory)) continue;
    regular(directory, true);
    for (const file of fs.readdirSync(directory)) regular(path.join(directory, file));
  }
  const data = validateDataset(root);
  const files = new Map(), patterns = publicationPatterns(root);
  const privateBatchIds = [...(data.coverage.ingestion_batches ?? []), ...data.problemAnalyses.flatMap(c => c.ingestion_batches ?? [])]
    .map(batch => batch.id).sort((a, b) => b.length - a.length);
  const batchPatterns = privateBatchIds.map(id => new RegExp(`(?<![A-Za-z0-9-])${id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?![A-Za-z0-9-])`));
  const projectText = value => {
    let text = publicCopy(value);
    for (const id of privateBatchIds) {
      const escaped = id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      text = text.replace(new RegExp(`(?<![A-Za-z0-9-])${escaped}(?![A-Za-z0-9-])`, 'g'), '[local batch reference not distributed]');
    }
    return text;
  };
  const project = (name, value) => {
    const {document, many} = documentForFile(name);
    return many ? value.map(item => policy.project(document, item, projectText)) : policy.project(document, value, projectText);
  };
  const add = (name, value) => {
    assert(approvedFile(name), 'Unapproved public data file');
    const text = typeof value === 'string' ? value : json(project(name, value));
    assert(!batchPatterns.some(pattern => pattern.test(text)), `${name}: unprojected local batch reference`);
    assertPublicText(text, name, patterns); files.set(name, text);
  };
  add('README.md', notice);
  add('manifest.json', data.manifest);
  for (const key of ['sources', 'ciphers', 'variants']) add(key + '.json', data[key]);
  for (const record of data.results) add('results/' + record.id + '.json', record);
  add('coverage.json', {...data.coverage, ingestion_batches: data.coverage.ingestion_batches ?? []});
  add('witnesses.json', readJson(path.join(locations.cryptanalysis, 'witnesses.json')));
  for (const folder of ['entries', 'result-families', 'presentation', 'problem-results', 'problem-analyses']) {
    const directory = path.join(locations.cryptanalysis, folder);
    if (!fs.existsSync(directory)) continue;
    for (const filename of fs.readdirSync(directory).sort()) {
      if (filename === 'README.md' && folder === 'presentation') continue;
      assert(approvedFile(folder + '/' + filename), `${folder}: unapproved input file`);
      const input = path.join(directory, filename);
      assert(!fs.lstatSync(input).isSymbolicLink(), 'Snapshot export refuses symlink inputs');
      if (folder === 'entries') {
        const entries = fs.readFileSync(input, 'utf8').split(/\r?\n/).filter(line => line.trim()).map(JSON.parse)
          .map(entry => policy.project('entry', entry, projectText));
        add(folder + '/' + filename, entries.map(entry => JSON.stringify(entry)).join('\n') + '\n');
      } else add(folder + '/' + filename, readJson(input));
    }
  }
  const fileHashes = Object.fromEntries([...files].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([name, bytes]) => [name, sha256(bytes)]));
  files.set('publication.json', json({schema_version: 1, profile: 'public', license: 'CC-BY-4.0',
    counts: counts(data), scientific_sha256: scientificDigest(data, root), files: fileHashes,
    data_sha256: sha256(json(fileHashes))}));
  return {files, counts: counts(data)};
}

function validatePublishedDataset(root, {directory = resolvePaths(root, 'public').cryptanalysis} = {}) {
  const policy = createPublicationPolicy(root);
  const publication = readJson(path.join(directory, 'publication.json'));
  shape(publication, ['schema_version', 'profile', 'license', 'counts', 'scientific_sha256', 'files', 'data_sha256'], 'publication');
  assert.equal(publication.schema_version, 1, 'Unknown snapshot format');
  assert.equal(publication.profile, 'public'); assert.equal(publication.license, 'CC-BY-4.0');
  assert(publication.files && !Array.isArray(publication.files) && typeof publication.files === 'object', 'Missing publication file list');
  const declared = Object.keys(publication.files).sort();
  assert(declared.every(approvedFile), 'Unapproved file in publication manifest');
  assert.deepEqual(fileInventory(directory).sort(), [...declared, 'publication.json'].sort(), 'Snapshot file inventory mismatch');
  const patterns = publicationPatterns(root);
  for (const name of declared) {
    const bytes = fs.readFileSync(path.join(directory, name));
    assert.equal(sha256(bytes), publication.files[name], `${name}: snapshot fingerprint mismatch`);
    assertPublicText(bytes.toString('utf8'), name, patterns);
  }
  assert.equal(sha256(json(publication.files)), publication.data_sha256, 'Snapshot revision mismatch');
  validatePublicShape(directory, root, policy);
  const data = validateDataset(root, {profile: 'public', dataDirectory: directory});
  assert.deepEqual(counts(data), publication.counts, 'Published counts mismatch');
  assert.equal(scientificDigest(data, root), publication.scientific_sha256, 'Published scientific payload mismatch');
  return {data, publication};
}

function checkExport(root) {
  const expected = makePublishedFiles(root), directory = resolvePaths(root, 'public').cryptanalysis;
  validatePublishedDataset(root);
  assert.deepEqual(fileInventory(directory).sort(), [...expected.files.keys()].sort(), 'Published export inventory is stale');
  for (const [name, text] of expected.files) assert(fs.readFileSync(path.join(directory, name), 'utf8') === text, `${name}: published export is stale; run export:analyses`);
  return expected.counts;
}

function exportPublishedDataset(root) {
  const {files, counts: summary} = makePublishedFiles(root);
  const workspace = path.join(root, '.local/publication');
  fs.mkdirSync(workspace, {recursive: true});
  const stage = fs.mkdtempSync(path.join(workspace, 'staging-'));
  for (const [name, text] of files) {
    const file = path.join(stage, name); fs.mkdirSync(path.dirname(file), {recursive: true});
    fs.writeFileSync(file, text, {flag: 'wx'});
  }
  validatePublishedDataset(root, {directory: stage});
  const target = resolvePaths(root, 'public').cryptanalysis;
  fs.mkdirSync(path.dirname(target), {recursive: true});
  let backup;
  if (fs.existsSync(target)) {
    assert(!fs.lstatSync(target).isSymbolicLink(), 'Cannot replace a redirected public snapshot');
    backup = fs.mkdtempSync(path.join(workspace, 'previous-'));
    fs.renameSync(target, path.join(backup, 'snapshot'));
  }
  try { fs.renameSync(stage, target); }
  catch (error) {
    if (backup) fs.renameSync(path.join(backup, 'snapshot'), target);
    throw error;
  }
  // Stage validation completed before replacement. The previous generated
  // snapshot is only a transaction rollback, not a second source-history store.
  if (backup) fs.rmSync(backup, {recursive: true});
  return summary;
}

module.exports = {makePublishedFiles, validatePublishedDataset, checkExport, exportPublishedDataset,
  fileInventory, approvedFile, counts, scientificDigest, validatePublicShape};
